"""Chrome extension <> Studio synchronization.

Only Chrome-originated, paired requests may mutate the extension state. Studio
may change configuration/rules but never grants/revokes Chrome permissions.
Pairing requires an on-screen code generated by Studio, entered in extension
Options, and is bound to a specific Chrome extension ID.
"""
from __future__ import annotations
import json
import os
import re
import secrets
import tempfile
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent / '.studio_runtime'
CONFIG = ROOT / 'extension-shared.json'
AUTH = ROOT / 'extension-private.json'
STUDIO_ORIGINS = frozenset(('http://localhost:1420','http://127.0.0.1:1420',
                            'tauri://localhost','http://tauri.localhost','https://tauri.localhost'))
EXT_RE = re.compile(r'chrome-extension://([a-p]{32})$')
KEYS = ('rules','serverUrl','kwtLocalUrl','kwtLocalModel',
        'kwtSiteOriginsV3','kwtImageHostOriginsV3','kwtMissingImageHostsV1')
DEFAULTS = {'rules':[], 'serverUrl':'http://127.0.0.1:8765',
            'kwtLocalUrl':'http://127.0.0.1:18080/v1','kwtLocalModel':'gemma4-12b-local',
            'kwtSiteOriginsV3':[],'kwtImageHostOriginsV3':[],'kwtMissingImageHostsV1':[]}
lock=threading.RLock()
pair_code=None
pair_expiry=0
pair_attempts=0
last_seen=0
permissions=[]

def read(path, fallback):
    try:
        data=json.loads(path.read_text(encoding='utf-8'))
        return data if isinstance(data,dict) else fallback
    except (OSError,ValueError):return fallback

def atomic(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp=tempfile.mkstemp(dir=path.parent,prefix='.'+path.name+'.',suffix='.tmp')
    try:
        with os.fdopen(fd,'w',encoding='utf-8') as f:
            json.dump(obj,f,ensure_ascii=False,indent=2);f.write('\n');f.flush();os.fsync(f.fileno())
        os.replace(temp,path)
    finally:
        if os.path.exists(temp):os.unlink(temp)

def validate_url(raw, suffix=''):
    s=str(raw).strip().rstrip('/')
    pattern=r'http://(?:localhost|127\.0\.0\.1)(?::\d{2,5})?'+suffix
    if not re.fullmatch(pattern,s):raise ValueError('서버는 로컬 주소(localhost/127.0.0.1)만 허용합니다.')
    return s

def origins(raw):
    if not isinstance(raw,list):raise ValueError('사이트 출처는 배열이어야 합니다.')
    out=[]
    for entry in raw[:300]:
        item=str(entry).strip().removesuffix('/*').rstrip('/')
        if not re.fullmatch(r'https?://[A-Za-z0-9.\-]+(?::\d{1,5})?',item):continue
        if item.lower().startswith(('http://127.','http://localhost','http://0.0.0.0','http://169.254.')):continue
        if item not in out:out.append(item)
    return out

def normalize(data, base=None, editable_only=False):
    if not isinstance(data,dict):raise ValueError('설정 객체가 필요합니다.')
    result=dict(DEFAULTS if base is None else base)
    allowed=KEYS[:4] if editable_only else KEYS
    for key in allowed:
        if key not in data:continue
        value=data[key]
        if key=='rules':
            if not isinstance(value,list) or len(value)>500:raise ValueError('규칙은 최대 500개입니다.')
            rules=[];seen=set()
            for i,r in enumerate(value):
                if not isinstance(r,dict):raise ValueError('수집 규칙 형식이 잘못되었습니다.')
                rid=str(r.get('id') or f'studio-rule-{i}').strip()[:100]
                if not rid or rid in seen:raise ValueError('규칙 ID 중복/누락')
                seen.add(rid)
                name=str(r.get('name') or '')[:150]
                pattern=str(r.get('pattern') or '').strip()[:1400]
                selector=str(r.get('selector') or '').strip()[:1800]
                if not pattern or not selector:raise ValueError('URL 패턴과 CSS 선택자를 입력하세요.')
                # Keep unrecognized rule fields for backward compatibility.
                rules.append({**r,'id':rid,'name':name,'pattern':pattern,'selector':selector,
                              'enabled':bool(r.get('enabled',True)), 'autoSend':bool(r.get('autoSend',True))})
            result[key]=rules
        elif key=='serverUrl':result[key]=validate_url(value)
        elif key=='kwtLocalUrl':result[key]=validate_url(value,r'(?:/v1)?')
        elif key=='kwtLocalModel':
            s=str(value).strip()
            if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._:/-]{0,99}',s):raise ValueError('잘못된 모델 ID')
            result[key]=s
        else:result[key]=origins(value)
    return result

def _studio(headers):
    origin=headers.get('Origin','')
    if origin and origin not in STUDIO_ORIGINS:raise PermissionError('허용되지 않은 Studio 출처')
    if headers.get('X-KWT-Studio')!='1':raise PermissionError('Studio 요청 헤더가 없습니다.')

def _chrome_id(headers, optional=False):
    origin=headers.get('Origin','')
    m=EXT_RE.fullmatch(origin) if origin else None
    if not m and not optional:raise PermissionError('Chrome 확장 프로그램에서만 연결할 수 있습니다.')
    return m.group(1) if m else None

def _client(headers, obj):
    state=read(AUTH,{})
    ext_id=str(obj.get('extension_id',''))
    if not re.fullmatch(r'[a-p]{32}',ext_id):raise PermissionError('확장앱 ID가 올바르지 않습니다.')
    origin_id=_chrome_id(headers,optional=True)
    if origin_id and origin_id!=ext_id:raise PermissionError('확장앱 Origin 불일치')
    if ext_id!=state.get('extension_id') or not secrets.compare_digest(str(headers.get('X-KWT-Extension-Key','')),str(state.get('token','!'))):
        raise PermissionError('확장 프로그램 연결 인증 실패')
    return ext_id

def _reply(revision, settings, **extra):return {'revision':revision,'settings':settings,**extra}

def get(path,query,headers):
    global pair_code
    _studio(headers)
    with lock:
        state=read(CONFIG,{'revision':0,'settings':dict(DEFAULTS)})
        auth=read(AUTH,{})
        if path=='/api/extension/studio/state':
            return {'paired':bool(auth.get('extension_id')),'extension_id':auth.get('extension_id',''),
                    'revision':state.get('revision',0),'settings':state.get('settings',dict(DEFAULTS)),
                    'connected':bool(last_seen and time.time()-last_seen<150),
                    'last_seen':last_seen,'granted_origins':list(permissions),
                    'pair_code_active':bool(pair_code and time.time()<pair_expiry)}
    raise ValueError('알 수 없는 확장앱 조회 요청')

def post(path,body,headers):
    global pair_code,pair_expiry,pair_attempts,last_seen,permissions
    with lock:
        if path.startswith('/api/extension/studio/'):
            _studio(headers)
            if path=='/api/extension/studio/pair-code':
                if read(AUTH,{}).get('extension_id'):
                    raise ValueError('이미 연결되었습니다. 새로 연결하려면 먼저 연결을 해제하세요.')
                pair_code=f'{secrets.randbelow(100000000):08d}'
                pair_expiry=time.time()+600;pair_attempts=0
                return {'code':pair_code,'expires_seconds':600}
            if path=='/api/extension/studio/unpair':
                atomic(AUTH,{})
                pair_code=None;last_seen=0;permissions=[]
                return {'unpaired':True}
            if path=='/api/extension/studio/save':
                st=read(CONFIG,{'revision':0,'settings':dict(DEFAULTS)})
                if int(body.get('base_revision',-1))!=st.get('revision',0):
                    raise RuntimeError('다른 화면에서 설정이 바뀌었습니다. 새로고침 후 다시 저장하세요.')
                settings=normalize(body.get('settings',{}),st.get('settings',dict(DEFAULTS)),editable_only=True)
                if settings!=st.get('settings'):
                    st={'revision':st['revision']+1,'settings':settings}
                    atomic(CONFIG,st)
                return _reply(st['revision'],st['settings'])
            raise ValueError('지원하지 않는 Studio 확장앱 요청')
        if path=='/api/extension/client/pair':
            cid=str(body.get('extension_id',''))
            origin_id=_chrome_id(headers,optional=True)
            if not re.fullmatch(r'[a-p]{32}',cid) or (origin_id and origin_id!=cid):
                raise PermissionError('확장 프로그램 ID/Origin 불일치')
            if read(AUTH,{}).get('extension_id'):raise ValueError('이미 다른 확장앱이 연결되어 있습니다.')
            if not pair_code or time.time()>pair_expiry or pair_attempts>=5:
                raise PermissionError('연결 코드가 없거나 만료되었습니다. Studio에서 새 코드를 생성하세요.')
            pair_attempts+=1
            if not secrets.compare_digest(str(body.get('code','')),pair_code):
                raise PermissionError('연결 코드가 올바르지 않습니다.')
            secret=secrets.token_urlsafe(32)
            atomic(AUTH,{'extension_id':cid,'token':secret})
            pair_code=None;pair_attempts=0;last_seen=time.time()
            return {'token':secret,'revision':0}
        if path=='/api/extension/client/sync':
            _client(headers,body)
            st=read(CONFIG,{'revision':0,'settings':dict(DEFAULTS)})
            revision=int(st.get('revision',0))
            client_rev=int(body.get('revision',0))
            incoming=normalize(body.get('settings',{}),dict(DEFAULTS))
            if revision==0 or client_rev==revision:
                if incoming!=st.get('settings'):
                    st={'revision':revision+1,'settings':incoming}
                    atomic(CONFIG,st)
                    revision=st['revision']
            # Otherwise server state wins, so pending Studio changes aren't overwritten.
            origins_in=body.get('granted_origins',[])
            permissions=origins(origins_in) if isinstance(origins_in,list) else []
            last_seen=time.time()
            return _reply(revision,st['settings'])
        raise ValueError('알 수 없는 확장앱 동기화 요청')
